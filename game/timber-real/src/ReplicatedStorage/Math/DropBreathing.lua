-- Devolve o u cru do frame, ciclando mod nFrames (índice 1-based).
function DropBreathing.ProximoU(frameIndex: number): number
	local n = DropBreathing.nFrames
	local i = ((frameIndex - 1) % n) + 1
	return DropBreathing.u[i]
end

-- Jitter normalizado ∈ [-1, 1] a partir do frame: (u - 0.5) * 2.
-- Multiplique pela amplitude (ex.: Config.Toco.JITTER) e some a 1 para
-- modular um tempo base: intervalo = BASE * (1 + JitterNormalizado(i) * JITTER).
function DropBreathing.JitterNormalizado(frameIndex: number): number
	return (DropBreathing.ProximoU(frameIndex) - 0.5) * 2
end

-- Mapeia frame → dict compatível com RngPesado.SortearChave
-- ids do Catalogo.Capim: 1=Comum 2=Premium 3=Raro
function DropBreathing.PesosComoDict(frameIndex: number): { [number]: { peso: number } }
	local n = DropBreathing.nFrames
	local i = ((frameIndex - 1) % n) + 1
	local f = DropBreathing.frames[i]
	return {
		[1] = { peso = f.comum },
		[2] = { peso = f.premium },
		[3] = { peso = f.raro },
	}
end

